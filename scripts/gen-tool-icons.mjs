// Generates src/data/toolIcons.js from the simple-icons dev dependency.
//
// Why generate instead of importing at runtime: simple-icons ships ~3k icons;
// we need ~40. This bakes only those into a ~12KB module, so `simple-icons`
// stays a devDependency and never reaches the bundle.
//
// Run after changing TOOLS below:  node scripts/gen-tool-icons.mjs
import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

// slug -> simple-icons export name. The slug is what src/data.js refers to.
const FROM_SIMPLE_ICONS = {
  python: 'siPython',
  pandas: 'siPandas',
  numpy: 'siNumpy',
  scikitlearn: 'siScikitlearn',
  tensorflow: 'siTensorflow',
  postgresql: 'siPostgresql',
  sqlite: 'siSqlite',
  supabase: 'siSupabase',
  redis: 'siRedis',
  sqlalchemy: 'siSqlalchemy',
  metabase: 'siMetabase',
  superset: 'siApachesuperset',
  streamlit: 'siStreamlit',
  plotly: 'siPlotly',
  d3: 'siD3',
  jupyter: 'siJupyter',
  git: 'siGit',
  github: 'siGithub',
  docker: 'siDocker',
  fastapi: 'siFastapi',
  react: 'siReact',
  nextjs: 'siNextdotjs',
  selenium: 'siSelenium',
  vercel: 'siVercel',
  render: 'siRender',
  maplibre: 'siMaplibre',
  googlesheets: 'siGooglesheets',
}

// Tools with no trustworthy open glyph (most were pulled from simple-icons over
// trademark policy). Rather than ship an approximation of someone's registered
// mark, these render as a monogram tile in the brand's colour.
const MONOGRAMS = {
  powerbi: { title: 'Power BI', hex: 'E8A317', mono: 'BI' },
  tableau: { title: 'Tableau', hex: '1F77B4', mono: 'Tb' },
  excel: { title: 'Microsoft Excel', hex: '217346', mono: 'Xl' },
  spss: { title: 'IBM SPSS', hex: '0530AD', mono: 'SP' },
  stata: { title: 'Stata', hex: '1A5F7A', mono: 'St' },
  sql: { title: 'SQL', hex: '0C7D9D', mono: 'SQL' },
  postgis: { title: 'PostGIS', hex: '2E7D32', mono: 'GIS' },
  surveycto: { title: 'SurveyCTO', hex: 'E8690B', mono: 'sCTO' },
  kobo: { title: 'Kobo Toolbox', hex: '2095F3', mono: 'KT' },
}

const icons = {}
for (const [slug, key] of Object.entries(FROM_SIMPLE_ICONS)) {
  const icon = si[key]
  if (!icon) {
    console.error(`MISSING in simple-icons: ${key} (slug ${slug})`)
    process.exitCode = 1
    continue
  }
  icons[slug] = { title: icon.title, hex: icon.hex, path: icon.path }
}
for (const [slug, def] of Object.entries(MONOGRAMS)) icons[slug] = def

// Vercel/Next/GitHub are near-black; unreadable on the dark theme. Give those a
// light-theme hex and a dark-theme override.
const DARK_OVERRIDES = { vercel: 'FFFFFF', nextjs: 'FFFFFF', github: 'E6EDF3', render: 'FFFFFF', numpy: '7AB7E8', pandas: '8E9BE8' }
for (const [slug, hex] of Object.entries(DARK_OVERRIDES)) {
  if (icons[slug]) icons[slug].darkHex = hex
}

const body = Object.entries(icons)
  .map(([slug, v]) => `  ${slug}: ${JSON.stringify(v)},`)
  .join('\n')

writeFileSync(
  'src/data/toolIcons.js',
  `// GENERATED by scripts/gen-tool-icons.mjs — do not edit by hand.
// Brand glyphs from simple-icons (CC0); monogram entries are plain lettermarks
// for tools whose marks are not available under an open licence.
export const toolIcons = {
${body}
}
`,
)
console.log(`wrote src/data/toolIcons.js — ${Object.keys(icons).length} icons`)
